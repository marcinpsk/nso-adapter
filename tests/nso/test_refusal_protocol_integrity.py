"""Public byte-integrity checks for the two generated artifacts."""

import hashlib
from pathlib import Path

import pytest

from nso_adapter.nso import refusal_protocol as protocol

_MODULE_PATH = Path(protocol.__file__)
_CORPUS_PATH = _MODULE_PATH.with_name("refusal_protocol_corpus.json")
_BEGIN = b"# BEGIN REFUSAL PROTOCOL INTEGRITY\n"
_END = b"# END REFUSAL PROTOCOL INTEGRITY\n"
_GENERATED = b"# GENERATED by tools/gen_refusal_protocol.py from protocols/refusal/. Do not edit: regenerate.\n"


def _assert_integrity(module_path, corpus_path):
    module = module_path.read_bytes()
    corpus = corpus_path.read_bytes()
    assert module.count(_BEGIN) == module.count(_END) == 1, "Require one integrity header"
    start = module.index(_BEGIN)
    end = module.index(_END) + len(_END)
    lines = module[start:end].splitlines(keepends=True)
    assert len(lines) == 6 and lines[:2] == [_BEGIN, _GENERATED] and lines[-1] == _END
    digests = {}
    for label, line in zip((b"source", b"body", b"corpus"), lines[2:5], strict=True):
        prefix = b"# " + label + b"-sha256: "
        assert line.startswith(prefix) and line.endswith(b"\n"), "Invalid digest field"
        digest = line[len(prefix) : -1]
        assert len(digest) == 64 and set(digest) <= set(b"0123456789abcdef"), "Invalid SHA-256 value"
        digests[label] = digest.decode("ascii")
    body = module[:start] + module[end:]
    assert hashlib.sha256(body).hexdigest() == digests[b"body"], "Module body digest mismatch"
    assert hashlib.sha256(corpus).hexdigest() == digests[b"corpus"], "Corpus digest mismatch"


def test_refusal_protocol_artifact_integrity():
    _assert_integrity(_MODULE_PATH, _CORPUS_PATH)


@pytest.mark.parametrize("mutation", ["catalog", "comment", "corpus"])
def test_refusal_protocol_artifact_integrity_detects_byte_change(tmp_path, mutation):
    module = _MODULE_PATH.read_bytes()
    corpus = _CORPUS_PATH.read_bytes()
    if mutation == "catalog":
        message = next(iter(protocol.MESSAGES.values())).text.encode()
        assert message in module
        module = module.replace(message, b"placeholder-altered-catalog-message", 1)
    elif mutation == "comment":
        module += b"\n# Placeholder whitespace change.\n"
    else:
        corpus += b"\n"
    module_path = tmp_path / "refusal_protocol.py"
    corpus_path = tmp_path / "refusal_protocol_corpus.json"
    module_path.write_bytes(module)
    corpus_path.write_bytes(corpus)
    with pytest.raises(AssertionError, match="digest mismatch"):
        _assert_integrity(module_path, corpus_path)
