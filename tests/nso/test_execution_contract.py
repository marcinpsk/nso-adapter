import copy
import hashlib
import json
import re
from pathlib import Path

import pytest

from nso_adapter.nso import execution_contract as contract
from nso_adapter.nso.origins import OVERLAY_GRAIN

_MODULE = Path(contract.__file__)
_HEADER = re.compile(
    rb"# BEGIN EXECUTION CONTRACT INTEGRITY\n"
    rb"# GENERATED by tools/gen_execution_contract.py from protocols/execution/. Do not edit: regenerate.\n"
    rb"# source-sha256: ([0-9a-f]{64})\n"
    rb"# body-sha256: ([0-9a-f]{64})\n"
    rb"# END EXECUTION CONTRACT INTEGRITY\n"
)


def _assert_integrity(module):
    matches = list(_HEADER.finditer(module))
    assert len(matches) == 1
    header = matches[0]
    assert header.start() == sum(len(line) for line in module.splitlines(keepends=True)[:2])
    body = module[: header.start()] + module[header.end() :]
    assert hashlib.sha256(body).hexdigest().encode() == header[2], "Module body digest mismatch"


def test_execution_contract_integrity():
    _assert_integrity(_MODULE.read_bytes())


@pytest.mark.parametrize("mutation", ["rule", "metadata", "comment"])
def test_execution_contract_integrity_detects_stale_copy(mutation):
    module = _MODULE.read_bytes()
    if mutation == "rule":
        module = module.replace(b"unknown settlement carrier", b"changed settlement carrier", 1)
    elif mutation == "metadata":
        module = module.replace(b"bgp_count_by_outcome", b"changed_count_by_outcome", 1)
    else:
        module += b"\n# Placeholder changed comment.\n"
    with pytest.raises(AssertionError, match="digest mismatch"):
        _assert_integrity(module)


def test_overlay_grain_is_a_projection_of_execution_metadata():
    assert {subject: list(grain) for subject, grain in OVERLAY_GRAIN.items()} == contract.METADATA["overlay_grain"]


def test_installed_contract_accepts_settlement_fixture():
    fixture = Path(__file__).parents[1] / "fixtures/refusal_settlement.json"
    scenario = json.loads(fixture.read_text())["bgp"]
    outcomes = []
    for item in scenario["expected"]:
        outcome = {key: value for key, value in item.items() if key not in {"outcome", "cause"}}
        outcome.update(disposition=item["outcome"], refusals=[scenario["refusal"]] if item["cause"] else [])
        outcomes.append(outcome)
    result = {
        "row_outcomes": outcomes,
        "refusals": [
            {
                **scenario["refusal"],
                "logical_rows": [
                    {key: value for key, value in outcomes[0].items() if key not in {"disposition", "refusals"}}
                ],
                "provenance": "current",
                "sender_phase": "commit",
            }
        ],
        "settlement_owners": [{**outcomes[0]["carrier"], "disposition": "refused"}],
        "bgp_count_by_outcome": {"in_sync": 0, "apply_failed": 1, "not_applied": 0, "unavailable": 0},
        "commit_acknowledged": False,
    }
    assert contract.validate_result(result, sections=("bgp",)) is result
    stale_count = copy.deepcopy(result)
    stale_count["bgp_count_by_outcome"]["apply_failed"] = 0
    with pytest.raises(contract.ContractError, match="carrier outcome count mismatch"):
        contract.validate_result(stale_count, sections=("bgp",))
